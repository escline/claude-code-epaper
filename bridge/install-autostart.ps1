# Makes the bridge daemon start at logon, so the panel and Home Assistant keep
# showing last-known usage even when Claude Code is closed.
#
#   Install:   powershell -ExecutionPolicy Bypass -File bridge\install-autostart.ps1
#   Remove:    powershell -ExecutionPolicy Bypass -File bridge\install-autostart.ps1 -Uninstall
#
# Prefers a scheduled task (restarts the daemon if it dies), but that needs
# elevation on most machines. Falls back to a Startup-folder launcher, which
# needs no admin rights at all. Both run the daemon with no console window.
#
# Safe alongside the client auto-spawn: whichever daemon loses the race for
# port 8787 logs EADDRINUSE and exits.

[CmdletBinding()]
param([switch]$Uninstall)

$ErrorActionPreference = 'Stop'

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$script = Join-Path $here 'bridge.js'
$taskName = 'Claude ePaper Bridge'
$startupDir = [Environment]::GetFolderPath('Startup')
$vbsPath = Join-Path $startupDir 'claude-epaper-bridge.vbs'

if ($Uninstall) {
    $removed = @()
    if (Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue) {
        try {
            Unregister-ScheduledTask -TaskName $taskName -Confirm:$false
            $removed += 'scheduled task'
        } catch { Write-Warning "could not remove scheduled task: $($_.Exception.Message)" }
    }
    if (Test-Path $vbsPath) { Remove-Item $vbsPath -Force; $removed += 'startup launcher' }
    if ($removed.Count) { Write-Host "Removed: $($removed -join ', ')" }
    else { Write-Host 'Nothing was installed.' }
    return
}

if (-not (Test-Path $script)) { throw "bridge.js not found at $script" }
$node = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $node) { throw 'node not found on PATH' }

Write-Host "node:   $node"
Write-Host "script: $script`n"

# --- preferred: scheduled task -------------------------------------------
$installed = $null
foreach ($logon in 'S4U', 'Interactive') {
    try {
        $action = New-ScheduledTaskAction -Execute $node `
            -Argument "`"$script`" daemon" -WorkingDirectory $here
        # Delay so the network is up before the first MQTT connect. mqtt.js
        # retries regardless; this just keeps the log clean.
        $trigger = New-ScheduledTaskTrigger -AtLogOn
        $trigger.Delay = 'PT30S'
        $settings = New-ScheduledTaskSettingsSet `
            -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
            -ExecutionTimeLimit ([TimeSpan]::Zero) `
            -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1) `
            -MultipleInstances IgnoreNew
        $principal = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\$env:USERNAME" `
            -LogonType $logon -RunLevel Limited

        Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger `
            -Settings $settings -Principal $principal -Force -ErrorAction Stop | Out-Null

        $installed = "scheduled task (logon type $logon)"
        break
    } catch {
        Write-Host "scheduled task via $logon unavailable: $($_.Exception.Message.Trim())"
    }
}

# --- fallback: Startup folder, no admin needed ---------------------------
if (-not $installed) {
    Write-Host "`nFalling back to the Startup folder (no admin required)."
    # WScript.Shell Run with window style 0 keeps node windowless. The daemon
    # resolves its config and log from __dirname, so the working directory here
    # does not matter.
    $vbs = @"
' Starts the Claude e-paper bridge daemon with no console window.
' Generated by install-autostart.ps1 - re-run that script if the repo moves.
Set sh = CreateObject("WScript.Shell")
sh.Run """$node"" ""$script"" daemon", 0, False
"@
    Set-Content -Path $vbsPath -Value $vbs -Encoding ASCII
    $installed = "startup launcher at $vbsPath"
}

Write-Host "`nInstalled: $installed"
